function sourceStamp() {
  const files = ['package.json', 'package-lock.json', 'tsconfig.app.json', 'tsconfig.node.json', 'tsconfig.json', 'nest-cli.json', 'vite.config.ts', 'client/index.html', 'client/public/favicon.svg'];
  const collect = folder => {
    for (const entry of fs.readdirSync(path.join(root, folder), { withFileTypes: true })) {
      const relative = `${folder}/${entry.name}`;
      if (entry.isDirectory()) collect(relative);
      else if (entry.isFile() && /\.(?:[cm]?js|tsx?|cs|css|json|sql|ps1|nsh|nsi|svg|png|ico)$/.test(entry.name)) files.push(relative);
    }
  };
  for (const folder of ['desktop', 'client/src', 'shared', 'server', 'scripts']) collect(folder);
  const hash = createHash('sha256');
  for (const file of files.sort()) {
    hash.update(file + '\0');hash.update(createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest());
  }
  return { sha256: hash.digest('hex'), files: files.length };
}
