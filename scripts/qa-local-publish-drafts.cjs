const assert = require('node:assert/strict'), fs = require('node:fs'), ts = require('typescript'), Module = require('node:module');
let userId = 'user-a', events = 0;
const storage = new Map();
global.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
global.window = { dispatchEvent: () => events++ };
const fixture = new Module('local-drafts');
fixture.require = id => { if (id === '@/api') return { getUser: () => ({ id: userId }) }; throw Error('Unexpected dependency'); };
fixture._compile(ts.transpileModule(fs.readFileSync('client/src/components/workspace/local-publish-drafts.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText,'local-drafts.cjs');
const { saveLocalDraft, readLocalDrafts, removeLocalDraft, draftPreferences, setDraftPreferences } = fixture.exports;
const config = { title:'测试',body:'正文',topics:['话题'],comment:'追评',options:{},covers:[{id:'private-handle',name:'cover.png',index:1}] };
const draft = { id:'draft-1',updatedAt:'first',title:'测试',config,configs:{a:config},accounts:[{id:'a',nickname:'名称',platform:'douyin'}],mediaType:'video',files:['sample.mp4'] };
assert.deepEqual(draftPreferences(), {auto:true,retain:true});
saveLocalDraft(draft); assert.equal(readLocalDrafts().length,1);
assert.equal(readLocalDrafts()[0].config.covers,undefined); assert.equal(readLocalDrafts()[0].configs.a.covers,undefined);
assert.equal(config.covers.length,1); assert.equal(readLocalDrafts()[0].config.comment,'追评');
setDraftPreferences({auto:false}); assert.deepEqual(draftPreferences(),{auto:false,retain:true});
userId='user-b'; assert.equal(readLocalDrafts().length,0); assert.equal(draftPreferences().auto,true);
userId='user-a'; saveLocalDraft({...draft,updatedAt:'newer'}); assert.equal(readLocalDrafts().length,1);
removeLocalDraft('draft-1','first'); assert.equal(readLocalDrafts().length,1);
removeLocalDraft('draft-1','newer'); assert.equal(readLocalDrafts().length,0);
storage.set('matrix-local-publish-drafts:user-a','invalid'); assert.equal(readLocalDrafts().length,0);
assert.equal(events,5);
