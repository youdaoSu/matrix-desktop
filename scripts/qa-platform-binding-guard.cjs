const { app, BrowserWindow, session } = require('electron');
const fs = require('node:fs'), os = require('node:os'), assert = require('node:assert/strict');
const { createPlatformBindingGuard, observeLoginRateNotice } = require('../desktop/platform-binding-guard.cjs');
const { createPlatformCheckCooldown } = require('../desktop/platform-check-cooldown.cjs');
const { chromiumUserAgent } = require('../desktop/browser-user-agent.cjs');
const beforeAgent = app.userAgentFallback;
app.userAgentFallback = chromiumUserAgent(beforeAgent, app.getName());
assert.equal(app.userAgentFallback.match(/Chrome\/[\d.]+/)[0], beforeAgent.match(/Chrome\/[\d.]+/)[0]);
assert.equal(chromiumUserAgent('Mozilla/5.0 (Windows NT 10.0; Win64; x64) 远效/2.10.0-rc.339 Chrome/152.0.7977.149 Electron/44.7.2 Safari/537.36', '远效'), chromiumUserAgent('Mozilla/5.0 (Windows NT 10.0; Win64; x64) 远效/2.10.0-rc.340 Chrome/152.0.7977.149 Electron/44.7.2 Safari/537.36', '远效'));
assert.equal(app.userAgentFallback.includes('Electron/'), false);
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'matrix-binding-guard-'));
app.setPath('userData', folder); app.disableHardwareAcceleration();
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async test => { for (let i = 0; i < 150; i++) { if (await test()) return; await delay(20); } throw Error('Binding guard fixture timeout'); };
app.whenReady().then(async () => {
  const windows = [], notices = [];
  let clock = 1000, requests = 0, limited = false;
  const file = path.join(folder, 'cooldown.json');
  const cooldown = createPlatformCheckCooldown({ file, now: () => clock });
  const guard = createPlatformBindingGuard({ cooldown, platforms: { douyin: { domain: 'douyin.com' } }, notify: value => notices.push(value) });
  const isolated = session.fromPartition('persist:synthetic-binding');
  await isolated.cookies.set({ url: 'https://creator.douyin.com/', name: 'sessionid', value: 'SYNTHETIC_ONLY', secure: true, httpOnly: true });
  await isolated.protocol.handle('https', request => {
    const url = new URL(request.url);
    assert.equal(url.hostname, 'creator.douyin.com');
    if (url.pathname === '/passport/web/check_qrconnect/') {
      requests++;
      return new Response(JSON.stringify({ data: { error_code: limited ? 7 : 0, message: limited ? '访问太频繁，请稍后再试' : '' } }), { headers: { 'content-type': 'application/json' } });
    }
    const sdk = `<script>setInterval(()=>fetch('/passport/web/check_qrconnect/').then(r=>r.json()).then(v=>{if(v.data.error_code===7){const notice=document.createElement('div');notice.className='message';notice.textContent=v.data.message;document.body.append(notice);setTimeout(()=>notice.remove(),60);}}),50);</script>`;
    return new Response('<meta charset=utf-8><main>' + '普通登录说明'.repeat(100) + '</main>' + (url.pathname === '/framed' ? '<iframe src="https://creator.douyin.com/frame"></iframe>' : sdk), { headers: { 'content-type': 'text/html' } });
  });
  const create = async route => {
    const win = new BrowserWindow({ show: false, webPreferences: { session: isolated, sandbox: true, nodeIntegration: false, contextIsolation: true, backgroundThrottling: false } });
    windows.push(win); await win.loadURL('https://creator.douyin.com' + route); return win;
  };
  try {
    const editor = await create('/editor');
    assert.equal(await editor.webContents.executeJavaScript('navigator.userAgent'), app.userAgentFallback);
    assert.equal(isolated.getUserAgent(), app.userAgentFallback);
    for (const route of ['/', '/framed']) {
      limited = false;
      const win = await create(route);
      guard.track('douyin', 'synthetic-session-0001', win.webContents);
      await until(() => requests > 2);
      // A brief classless notice generated by an HTTP 200/code 7 response.
      limited = true;
      await until(() => win.webContents.getURL() === 'about:blank');
      assert.equal(editor.webContents.getURL(), 'https://creator.douyin.com/editor');
      assert.equal(notices.at(-1).webContentsId, win.webContents.id);
      assert.equal(notices.at(-1).retryAt, clock + 3600000);
      const stopped = requests;
      // Editor deliberately remains active: pause must not touch this document.
      await editor.webContents.executeJavaScript('for(let id=1;id<100;id++)clearInterval(id);true');
      await delay(100); const settled = requests; await delay(180);
      assert.equal(requests, settled); assert.ok(settled >= stopped);
      assert.equal((await isolated.cookies.get({ url: 'https://creator.douyin.com/' })).find(c => c.name === 'sessionid').value, 'SYNTHETIC_ONLY');
      assert.equal(createPlatformCheckCooldown({ file, now: () => clock }).get('douyin').retryAt, clock + 3600000);
      guard.end(win.webContents, 'synthetic-session-0001'); win.close(); clock += 3600001;
    }
    limited = false;
    const unrelated = await create('/negative');
    await unrelated.webContents.executeJavaScript('for(let id=1;id<100;id++)clearInterval(id);true');
    for (const html of ['<div><article>访问太频繁，请稍后再试</article></div>', '<div class="comment-item">访问太频繁，请稍后再试</div>', '<div style="display:none">访问太频繁，请稍后再试</div>']) {
      await unrelated.webContents.executeJavaScript(`document.body.innerHTML=${JSON.stringify(html)};true`);
      assert.equal(await unrelated.webContents.executeJavaScriptInIsolatedWorld(991, [{ code: `(${observeLoginRateNotice.toString()})('fixture-stop',80)` }]), false);
    }
    guard.track('douyin', 'synthetic-session-0002', unrelated.webContents);
    guard.end(unrelated.webContents, 'synthetic-session-0002');
    await unrelated.webContents.executeJavaScript("const n=document.createElement('div');n.textContent='访问太频繁，请稍后再试';document.body.append(n);true");
    await delay(150);
    assert.notEqual(unrelated.webContents.getURL(), 'about:blank');
    assert.equal(cooldown.get('douyin'), undefined);
    console.log(JSON.stringify({ passed: true, http200BusinessDenialPaused: true, transientNoticeCaptured: true, childFrameCaptured: true, officialPollingStopped: true, unrelatedEditorRetained: true, cookiesRetained: true, lateNoticeAfterEndIgnored: true, realPlatformRequests: 0 }));
  } finally { for (const win of windows) if (!win.isDestroyed()) win.close(); }
}).then(() => app.quit()).catch(error => { console.error(error); app.exit(1); });
