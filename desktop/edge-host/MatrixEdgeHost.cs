  async Task WarmBlankRenderer() {
    // A never-shown WinForms controller reports a hidden document. Creator
    // apps can then defer previews/dialogs even after accepting a file. Realize
    // only about:blank once, clipped outside this parent's client area. Never
    // show an official/authenticated document, activate a window or take input.
    string source=browser.CoreWebView2.Source;
    if(!String.IsNullOrEmpty(source)&&source!="about:blank")throw new InvalidOperationException("初始化页面已变化");
    RECT client;if(!GetClientRect(parent,out client))throw new InvalidOperationException("父窗口已关闭");
    warmingRenderer=true;Enabled=false;
    try {
      SetWindowPos(Handle,IntPtr.Zero,client.Right+64,0,desiredWidth,desiredHeight,0x0014);
      Show();
      for(int step=0;step<20&&!closing&&!IsDisposed;step++) {
        if(await browser.CoreWebView2.ExecuteScriptAsync("document.visibilityState")=="\"visible\"")break;
        await Task.Delay(25);
      }
    } finally {
      if(!IsDisposed){Hide();Enabled=true;}
      appliedBounds=Rectangle.Empty;warmingRenderer=false;
    }
  }
  void ApplyBounds() {
    if(warmingRenderer)return;
    RECT client;
    if(!GetClientRect(parent,out client)) { Close(); return; }
    bool parentMinimized=IsIconic(parent);
    // Hidden publishers still need the real editor's responsive layout. A
    // minimized parent's client area is zero; clipping to it used to shrink
    // WebView2 to 1px and remove cover/upload controls during background work.
    // Preserve the requested viewport without making or activating a window.
    bool hiddenLayout=!desiredVisible||parentMinimized;
    int x=hiddenLayout?0:Math.Max(0,Math.Min(client.Right,desiredX)),y=hiddenLayout?0:Math.Max(0,Math.Min(client.Bottom,desiredY));
    int width=hiddenLayout?Math.Max(1,desiredWidth):Math.Max(0,Math.Min(desiredWidth,client.Right-x)),height=hiddenLayout?Math.Max(1,desiredHeight):Math.Max(0,Math.Min(desiredHeight,client.Bottom-y));
    var nextBounds=new Rectangle(x,y,Math.Max(1,width),Math.Max(1,height));
    if(nextBounds!=appliedBounds) {
      SetWindowPos(Handle,IntPtr.Zero,x,y,nextBounds.Width,nextBounds.Height,0x0010);
      appliedBounds=nextBounds;
    }
    bool show=desiredVisible&&width>1&&height>1&&initialized&&!parentMinimized;
    if(show&&!Visible) Show(); else if(!show&&Visible) Hide();
    // Electron may reinsert its renderer HWND above embedded children on
    // activation/restore. Raise only this visible child in its own parent;
    // HWND_TOP is not TOPMOST and SWP_NOACTIVATE never steals keyboard focus.
    if(show) SetWindowPos(Handle,IntPtr.Zero,0,0,0,0,0x0013);
  }
  static string StringValue(Dictionary<string,object> message,string key) { object value; return message.TryGetValue(key,out value)?Convert.ToString(value):""; }
  static int IntValue(Dictionary<string,object> message,string key) { object value; return message.TryGetValue(key,out value)?Convert.ToInt32(value):0; }
  // DOM.getDocument on a real creator app can contain megabytes of inline SVG,
  // styles and attributes. Matrix only needs the authored shadow roots.
  // Keep the bounded raw result native and send just that minimal topology over
  // the private pipe; never serialize page attributes or arbitrary page state.
  object CompactDocument(string raw) {
    if(raw.Length>16*1024*1024) throw new InvalidOperationException("官方组件文档过大，未执行控件操作");
    var parser=new JavaScriptSerializer { MaxJsonLength=16*1024*1024,RecursionLimit=256 };
    var document=parser.Deserialize<Dictionary<string,object>>(raw);
    object rootValue; if(!document.TryGetValue("root",out rootValue)) throw new InvalidOperationException("官方组件文档尚未就绪");
    var root=rootValue as Dictionary<string,object>;
    if(root==null) throw new InvalidOperationException("官方组件文档尚未就绪");
    var stack=new Stack<Dictionary<string,object>>();stack.Push(root);
    var hosts=new List<object>();int visited=0;
    while(stack.Count>0) {
      var node=stack.Pop();if(++visited>50000) throw new InvalidOperationException("官方组件节点过多，未执行控件操作");
      object shadowValue;
      if(node.TryGetValue("shadowRoots",out shadowValue)) {
        var compactRoots=new List<object>();var shadows=shadowValue as IEnumerable;
        if(shadows!=null) foreach(object item in shadows) {
          var shadow=item as Dictionary<string,object>;if(shadow==null)continue;
          string kind=StringValue(shadow,"shadowRootType");if(kind!="open"&&kind!="closed")continue;
          stack.Push(shadow);object backendId;
          if(shadow.TryGetValue("backendNodeId",out backendId))compactRoots.Add(new {backendNodeId=backendId,shadowRootType=StringValue(shadow,"shadowRootType")});
        }
        string name=StringValue(node,"nodeName");
        if(compactRoots.Count>0) {hosts.Add(new {nodeName=name,shadowRoots=compactRoots});if(hosts.Count>40)throw new InvalidOperationException("官方组件结构过于复杂，未执行操作");}
      }
      object childrenValue;
      if(node.TryGetValue("children",out childrenValue)) {var children=childrenValue as IEnumerable;if(children!=null)foreach(object item in children){var child=item as Dictionary<string,object>;if(child!=null)stack.Push(child);}}
    }
    return new {root=new {nodeName="#document",children=hosts}};
  }
  async void Command(Dictionary<string,object> message) {
    string id=StringValue(message,"id"),command=StringValue(message,"command");
    try {
      if(command=="close") { Close(); return; }
#if MATRIX_EDGE_QA
      if(command=="qa-layout") {
        RECT size; GetClientRect(Handle,out size);
        Emit(new { id=id,result=new {visible=Visible,width=size.Right,height=size.Bottom,parentMinimized=IsIconic(parent),topSibling=GetWindow(Handle,3)==IntPtr.Zero,audioMuted=initialized&&browser.CoreWebView2.IsMuted,fileChooserIntercepted=fileChooserIntercepted} }); return;
      }
#endif
      if(command=="bounds") {
        desiredX=IntValue(message,"x"); desiredY=IntValue(message,"y");
        int width=IntValue(message,"width"),height=IntValue(message,"height");
        // Effect cleanup may arrive between navigation and upload probing.
        // Its historical 1x1 hide must retain the last useful viewport, not
        // briefly turn the official page into a 2x2 CSS document at 70% zoom.
        if(width>1&&height>1) { desiredWidth=width; desiredHeight=height; }
        desiredVisible=width>1&&height>1&&StringValue(message,"visible").Equals("True",StringComparison.OrdinalIgnoreCase); ApplyBounds();
      } else {
        if(!initialized) throw new InvalidOperationException("官方页面尚未准备好");
        if(command=="navigate") {
          string url=StringValue(message,"url");if(!Official(url))throw new InvalidOperationException("仅允许视频号官方网址");
          pendingNavigationRequest=id;pendingNavigationUrl=url;
          try { browser.CoreWebView2.Navigate(url); }
          catch { if(pendingNavigationRequest==id){pendingNavigationRequest="";pendingNavigationUrl="";} throw; }
          Emit(new {id=id,result=new {ok=true,navigationRequestId=id}});return;
        }
        else if(command=="reload") browser.Reload();
        else if(command=="back") { if(browser.CanGoBack) browser.GoBack(); }
        else if(command=="forward") { if(browser.CanGoForward) browser.GoForward(); }
        else if(command=="zoom") { double zoom=Convert.ToDouble(message["zoom"]); browser.ZoomFactor=Math.Max(.5,Math.Min(1.5,zoom)); }
        else if(command=="profile") {
          string before=browser.CoreWebView2.Source;
          if(!Official(before)) throw new InvalidOperationException("官方页面校验失败");
          // Script is generated by the trusted native Matrix process, never web content.
          string result=await browser.CoreWebView2.ExecuteScriptAsync(StringValue(message,"script"));
          if(browser.CoreWebView2.Source!=before) throw new InvalidOperationException("官方页面正在切换，请稍后绑定");
          Emit(new { id=id,result=json.DeserializeObject(result) }); return;
        } else if(command=="dom") {
          string method=StringValue(message,"method"),before=browser.CoreWebView2.Source;
          if(!DomMethods.Contains(method)) throw new InvalidOperationException("不允许读取浏览器凭据或调用平台网络接口");
          object parameters; if(!message.TryGetValue("parameters",out parameters)) parameters=new Dictionary<string,object>();
          var parameterMap=parameters as Dictionary<string,object>;
          bool cleanup=method=="Page.setInterceptFileChooserDialog"&&parameterMap!=null&&StringValue(parameterMap,"enabled").Equals("False",StringComparison.OrdinalIgnoreCase);
          if(!Official(before)||(!cleanup&&DisplayUrl(before)!=StringValue(message,"expectedUrl"))) throw new InvalidOperationException("官方页面已变化，请重新读取");
          string result=await browser.CoreWebView2.CallDevToolsProtocolMethodAsync(method,json.Serialize(parameters));
          if(method=="Page.setInterceptFileChooserDialog"&&parameterMap!=null)fileChooserIntercepted=StringValue(parameterMap,"enabled").Equals("True",StringComparison.OrdinalIgnoreCase);
          if(!cleanup&&browser.CoreWebView2.Source!=before) throw new InvalidOperationException("官方页面正在切换，请等待新的编辑器");
          Emit(new { id=id,result=method=="DOM.getDocument"?CompactDocument(result):json.DeserializeObject(result) }); return;
        } else throw new InvalidOperationException("不支持的官方页面操作");
      }
      Emit(new { id=id,result=new { ok=true } });
    } catch(InvalidOperationException error) { Emit(new { id=id,error=error.Message }); }
    catch(Exception error) {
      string operation=command=="dom"&&DomMethods.Contains(StringValue(message,"method"))?StringValue(message,"method"):command;
      // Only a whitelisted operation name and HRESULT, never SDK exception text
      // (which can contain website URLs, field values or local paths).
      Emit(new { id=id,error="内嵌官方控件操作失败（"+operation+"，0x"+error.HResult.ToString("X8")+"），请重试；原账号数据未改变" });
    }
  }
  async Task ReadCommands() {
    while(!closing) {
      string line=await Console.In.ReadLineAsync();
      if(line==null) { if(!closing) BeginInvoke(new Action(Close));return; }
      if(line.Length>1048576) { BeginInvoke(new Action(Close));return; }
      try { var message=json.Deserialize<Dictionary<string,object>>(line);BeginInvoke(new Action(()=>Command(message))); }
      catch { /* Invalid transport input never reaches web content. */ }
    }
  }
  [STAThread] static int Main(string[] args) {
    try {
      // GUI-subsystem programs have redirected pipes but no console. Use the
      // inherited UTF-8 pipes without trying to configure a nonexistent console.
      Console.SetIn(new StreamReader(Console.OpenStandardInput(),new UTF8Encoding(false)));
      Console.SetOut(new StreamWriter(Console.OpenStandardOutput(),new UTF8Encoding(false)) { AutoFlush=true });
      if(args.Length!=2) return 2;
      IntPtr hwnd=new IntPtr(Int64.Parse(args[0])); if(!IsWindow(hwnd)) return 3;
      string dataFolder=Path.GetFullPath(args[1]);
      Application.EnableVisualStyles(); Application.SetCompatibleTextRenderingDefault(false);
      var host=new MatrixEdgeHost(hwnd,dataFolder);
      host.HandleCreated+=(sender,e)=> { var task=Task.Run(()=>host.ReadCommands()); };
      Application.Run(host); return 0;
    } catch { Console.Out.WriteLine("{\"event\":\"fatal\",\"error\":\"原生 Edge 嵌入控件启动失败，原账号数据未改变\"}");return 1; }
  }
