  static bool Official(string url) {
    Uri uri;
    return Uri.TryCreate(url,UriKind.Absolute,out uri) && uri.Scheme=="https" && String.IsNullOrEmpty(uri.UserInfo)
      && (uri.Host=="weixin.qq.com" || uri.Host.EndsWith(".weixin.qq.com",StringComparison.OrdinalIgnoreCase));
  }
  static string DisplayUrl(string url) { Uri uri; return Uri.TryCreate(url,UriKind.Absolute,out uri)?uri.GetLeftPart(UriPartial.Path):""; }
  void Emit(object message) { lock(outputLock) { Console.Out.WriteLine(json.Serialize(message)); Console.Out.Flush(); } }
  void Status(string error=null,bool navigationComplete=false) {
    Emit(new { @event="status",url=DisplayUrl(browser.Source==null?"":browser.Source.ToString()),title=initialized?browser.CoreWebView2.DocumentTitle:"视频号官方页面",
      ready=initialized,back=browser.CanGoBack,forward=browser.CanGoForward,error=error,navigationComplete=navigationComplete,navigationRequestId=activeNavigationRequest });
  }
  MatrixEdgeHost(IntPtr hwnd,string dataFolder) {
    parent=hwnd; profile=dataFolder;
    TopLevel=false; FormBorderStyle=FormBorderStyle.None; ShowInTaskbar=false; AutoScaleMode=AutoScaleMode.None;
    StartPosition=FormStartPosition.Manual; Bounds=new Rectangle(-20000,-20000,1,1);
    browser.Dock=DockStyle.Fill; Controls.Add(browser);
    // Electron can restore to the same CSS size. A renderer fingerprint then
    // emits no bounds command, even if a minimized parent clipped us to 1px.
    watchdog.Tick+=(sender,args)=> { if(!IsWindow(parent)) Close(); else ApplyBounds(); };
    Shown+=async(sender,args)=> {
      if(initializationStarted)return;initializationStarted=true;
      Emit(new { @event="initializing",stage="shown" }); Hide(); watchdog.Start();
      try {
        var environment=await CoreWebView2Environment.CreateAsync(null,profile);
        Emit(new { @event="initializing",stage="environment" });
        await browser.EnsureCoreWebView2Async(environment);
        var core=browser.CoreWebView2;
        // The native engine is a separate process: Electron's mute switch does
        // not silence it. Apply this before the first official navigation.
        core.IsMuted=true;
        core.Settings.AreHostObjectsAllowed=false;
        core.Settings.IsWebMessageEnabled=false;
        core.Settings.AreDevToolsEnabled=false;
        core.Settings.IsPasswordAutosaveEnabled=false;
        core.Settings.IsGeneralAutofillEnabled=false;
        await WarmBlankRenderer();
        if(closing||IsDisposed)return;
        // Only this one rendered-control event crosses the private native pipe.
        // Never forward general protocol events, URLs, file paths or storage.
        fileChooserReceiver=core.GetDevToolsProtocolEventReceiver("Page.fileChooserOpened");
        fileChooserReceiver.DevToolsProtocolEventReceived+=(s,e)=> {
          if(!fileChooserIntercepted||!Official(core.Source)||!String.IsNullOrEmpty(e.SessionId))return;
          try {
            string raw=e.ParameterObjectAsJson;if(raw.Length>4096)return;
            var item=json.Deserialize<Dictionary<string,object>>(raw);
            string frameId=StringValue(item,"frameId"),mode=StringValue(item,"mode");int backendId=IntValue(item,"backendNodeId");
            if(frameId.Length<1||frameId.Length>128||backendId<=0||(mode!="selectSingle"&&mode!="selectMultiple"))return;
            Emit(new {@event="dom-event",method="Page.fileChooserOpened",parameters=new {frameId=frameId,backendNodeId=backendId,mode=mode}});
          } catch { /* A malformed event cannot select any file. */ }
        };
#if MATRIX_EDGE_QA
        // Compiled only into a temporary QA executable, never the shipped host.
        // Local HTML fixtures use a fresh profile and no real platform credentials.
        string fixtures=Environment.GetEnvironmentVariable("MATRIX_EDGE_QA_FIXTURES");
        if(String.IsNullOrEmpty(fixtures)||!Directory.Exists(fixtures)||!Path.GetFullPath(fixtures).StartsWith(Path.GetTempPath(),StringComparison.OrdinalIgnoreCase)) throw new InvalidOperationException("临时测试目录无效");
        core.AddWebResourceRequestedFilter("https://channels.weixin.qq.com/*",CoreWebView2WebResourceContext.All);
        core.WebResourceRequested+=(s,e)=> {
          string fixturePath=new Uri(e.Request.Uri).AbsolutePath;
          string page=fixturePath.Contains("/post/create")?"editor.html":fixturePath.Contains("/post/list")?"list.html":"home.html";
          e.Response=environment.CreateWebResourceResponse(new MemoryStream(File.ReadAllBytes(Path.Combine(fixtures,page))),200,"OK","Content-Type: text/html; charset=utf-8\r\nCache-Control: no-store");
        };
#endif
        core.PermissionRequested+=(s,e)=> { e.State=CoreWebView2PermissionState.Deny; };
        core.DownloadStarting+=(s,e)=> { e.Cancel=true; };
        core.ServerCertificateErrorDetected+=(s,e)=> { e.Action=CoreWebView2ServerCertificateErrorAction.Cancel; };
        core.NavigationStarting+=(s,e)=> {
          if(!Official(e.Uri)) { e.Cancel=true; Status("已阻止非视频号官方网页的导航"); return; }
          if(e.NavigationId!=lastNavigationId) {
            // Correlate completion with the actual requested navigation, not
            // an old login document or an earlier request completing late.
            activeNavigationRequest=!String.IsNullOrEmpty(pendingNavigationRequest)&&new Uri(e.Uri).AbsoluteUri==new Uri(pendingNavigationUrl).AbsoluteUri?pendingNavigationRequest:"";
            if(!String.IsNullOrEmpty(activeNavigationRequest)){pendingNavigationRequest="";pendingNavigationUrl="";}
          }
          lastNavigationId=e.NavigationId;
        };
        core.NewWindowRequested+=(s,e)=> { e.Handled=true; Status("官方页面请求新窗口，请在当前页使用官方入口；未打开外部浏览器"); };
        core.SourceChanged+=(s,e)=>Status();
        core.HistoryChanged+=(s,e)=>Status();
        core.DocumentTitleChanged+=(s,e)=>Status();
        core.NavigationCompleted+=(s,e)=> { if(e.NavigationId==lastNavigationId) Status(e.IsSuccess?null:"官方页面加载失败（"+e.WebErrorStatus.ToString()+"）",true); };
        initialized=true;
        Emit(new { @event="ready",engine="webview2",embedded=GetParent(Handle)==parent,version=environment.BrowserVersionString });
        ApplyBounds(); core.Navigate("https://channels.weixin.qq.com/");
      } catch { Emit(new { @event="fatal",error="Edge WebView2 初始化失败，请检查运行时是否完整。原账号数据未改变。" }); Close(); }
    };
    FormClosed+=(sender,args)=> { closing=true; watchdog.Stop(); browser.Dispose(); };
  }
  protected override void OnHandleCreated(EventArgs args) {
    base.OnHandleCreated(args);
    long style=GetWindowLongPtr(Handle,-16).ToInt64();
    SetWindowLongPtr(Handle,-16,new IntPtr((style & ~0x80000000L)|0x40000000L));
    SetParent(Handle,parent);
    if(GetParent(Handle)!=parent) throw new InvalidOperationException("Native embedding failed");
    Emit(new { @event="initializing",stage="attached" });
  }
  protected override CreateParams CreateParams {
    get { var parameters=base.CreateParams;parameters.Parent=parent;parameters.Style=(parameters.Style & unchecked((int)~0x80000000))|0x40000000;return parameters; }
  }
